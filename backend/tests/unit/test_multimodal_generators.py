class TestCodeZIPGenerator:
    """Verify code ZIP generation with security checks."""

    def test_generate_zip_returns_valid_zip(self):
        """Generated bytes should be a valid ZIP file."""
        zip_bytes, file_list = CodeZIPGenerator.generate_zip_bytes(SAMPLE_UNIT_CONTENT)

        assert len(zip_bytes) > 0
        assert len(file_list) > 0
        assert "README.md" in file_list

        with zipfile.ZipFile(BytesIO(zip_bytes)) as zf:
            assert "README.md" in zf.namelist()

    def test_zip_contains_readme_with_content(self):
        """README.md should contain project description."""
        zip_bytes, _ = CodeZIPGenerator.generate_zip_bytes(SAMPLE_UNIT_CONTENT)

        with zipfile.ZipFile(BytesIO(zip_bytes)) as zf:
            readme = zf.read("README.md").decode("utf-8")
            assert "Python" in readme or "python" in readme.lower()
            assert "学习目标" in readme
            assert "运行方式" in readme

    def test_zip_contains_example_code_file(self):
        """ZIP should contain at least one example code file."""
        zip_bytes, file_list = CodeZIPGenerator.generate_zip_bytes(SAMPLE_UNIT_CONTENT)

        code_files = [f for f in file_list if f.endswith((".py", ".js"))]
        assert len(code_files) > 0

    def test_zip_does_not_contain_forbidden_extensions(self):
        """ZIP should not contain .sh, .bat, .exe, etc."""
        forbidden = {".sh", ".bat", ".cmd", ".ps1", ".exe", ".dll"}
        _, file_list = CodeZIPGenerator.generate_zip_bytes(SAMPLE_UNIT_CONTENT)

        for filename in file_list:
            ext = "." + filename.rsplit(".", 1)[-1] if "." in filename else ""
            assert ext.lower() not in forbidden, f"Forbidden extension: {filename}"

    def test_zip_respects_max_size(self):
        """ZIP should not exceed maximum size limit."""
        zip_bytes, _ = CodeZIPGenerator.generate_zip_bytes(SAMPLE_UNIT_CONTENT)

        assert len(zip_bytes) <= 500_000  # 500 KB max

    def test_zip_with_minimal_content(self):
        """ZIP generation should work with minimal content."""
        zip_bytes, file_list = CodeZIPGenerator.generate_zip_bytes(MINIMAL_UNIT_CONTENT)

        assert len(zip_bytes) > 0
        assert "README.md" in file_list

    def test_security_check_detects_forbidden_patterns(self):
        """The security check should detect forbidden patterns."""
        assert CodeZIPGenerator._contains_forbidden_patterns("rm -rf /")
        assert CodeZIPGenerator._contains_forbidden_patterns("subprocess.call('evil')")
        assert CodeZIPGenerator._contains_forbidden_patterns("eval('malicious')")
        assert not CodeZIPGenerator._contains_forbidden_patterns("print('hello')")
        assert not CodeZIPGenerator._contains_forbidden_patterns("def main():")


