class TestPPTXGenerator:
    """Verify PPTX generation from unit content."""

    def test_generate_pptx_bytes_returns_valid_pptx(self):
        """Generated bytes should be a valid PPTX file."""
        pptx_bytes = PPTXGenerator.generate_pptx_bytes(SAMPLE_UNIT_CONTENT)

        if pptx_bytes is None:
            pytest.skip("python-pptx not installed")

        assert len(pptx_bytes) > 0

        # Verify it's a valid PPTX (ZIP-based format)
        import zipfile

        with zipfile.ZipFile(BytesIO(pptx_bytes)) as zf:
            assert "ppt/presentation.xml" in zf.namelist()

    def test_generate_pptx_has_correct_slide_count(self):
        """PPTX should have slides for title, objectives, sections, tasks, and summary."""
        pptx_bytes = PPTXGenerator.generate_pptx_bytes(SAMPLE_UNIT_CONTENT)

        if pptx_bytes is None:
            pytest.skip("python-pptx not installed")

        from pptx import Presentation

        prs = Presentation(BytesIO(pptx_bytes))
        # Title + Objectives + 3 sections (each short enough for 1 slide) + Practice + Summary = 7
        assert len(prs.slides) >= 5

    def test_generate_pptx_with_minimal_content(self):
        """PPTX generation should work with minimal content."""
        pptx_bytes = PPTXGenerator.generate_pptx_bytes(MINIMAL_UNIT_CONTENT)

        if pptx_bytes is None:
            pytest.skip("python-pptx not installed")

        assert len(pptx_bytes) > 0
        from pptx import Presentation

        prs = Presentation(BytesIO(pptx_bytes))
        # At least a title slide
        assert len(prs.slides) >= 1

    def test_generate_pptx_title_matches_content(self):
        """The first slide title should come from the introduction."""
        pptx_bytes = PPTXGenerator.generate_pptx_bytes(SAMPLE_UNIT_CONTENT)

        if pptx_bytes is None:
            pytest.skip("python-pptx not installed")

        from pptx import Presentation

        prs = Presentation(BytesIO(pptx_bytes))
        first_slide = prs.slides[0]
        title_text = ""
        for shape in first_slide.shapes:
            if shape.has_text_frame:
                title_text = shape.text_frame.text
                break
        assert "Python" in title_text or "基础语法" in title_text


